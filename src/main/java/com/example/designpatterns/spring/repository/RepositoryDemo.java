package com.example.designpatterns.spring.repository;

import com.example.designpatterns.catalog.Category;
import com.example.designpatterns.catalog.PatternDemo;
import org.springframework.stereotype.Component;

import java.util.LinkedHashMap;
import java.util.Map;

/** Catalog entry for the Repository pattern. */
@Component
public class RepositoryDemo implements PatternDemo {

    private final BookService bookService;

    public RepositoryDemo(BookService bookService) {
        this.bookService = bookService;
    }

    @Override public String id() { return "repository"; }
    @Override public Category category() { return Category.SPRING; }
    @Override public String title() { return "Repository"; }

    @Override
    public String intent() {
        return "Mediate between the domain and data mapping layers using a collection-like "
                + "interface for accessing domain objects.";
    }

    @Override
    public Object run() {
        BookCatalog inMemory = new InMemoryBookCatalog();
        inMemory.save(new Book("A Wizard of Earthsea", "Ursula K. Le Guin", 1968));
        inMemory.save(new Book("The Dispossessed", "Ursula K. Le Guin", 1974));
        inMemory.save(new Book("Kindred", "Octavia E. Butler", 1979));

        Map<String, Object> result = new LinkedHashMap<>();
        result.put("fromH2ViaSpringData", bookService.byAuthor("ursula k. le guin")
                .stream().map(Book::toString).toList());
        result.put("fromHandWrittenInMemory", inMemory.findByAuthor("URSULA K. LE GUIN")
                .stream().map(Book::toString).toList());
        result.put("h2BookCount", bookService.all().size());
        result.put("note", "Both lists came from the same BookCatalog contract with the same "
                + "case-insensitive behaviour — one backed by H2 and generated by Spring Data, "
                + "one hand-written over an ArrayList.");
        return result;
    }
}
